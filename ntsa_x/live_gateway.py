"""Local-only streaming conversation bridge for an externally hosted inference model.

Research adapter, not the NTSA-X verified convergence engine. Dialogue is
unverified and is deliberately stored outside the verified Nexus DAG.
"""
from __future__ import annotations

from argparse import ArgumentParser
from contextlib import contextmanager
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from threading import Lock
from typing import Iterator
from urllib.error import HTTPError, URLError
from urllib.parse import urlsplit
from urllib.request import Request, HTTPRedirectHandler, build_opener
import json
import sqlite3
import re


SESSION = re.compile(r"^[A-Za-z0-9_-]{8,64}$")
MAX_INPUT = 4000
MAX_REPLY = 16000
MAX_BODY = 8192
SYSTEM_MESSAGE = (
    "You are the NTSA-X conversational research interface. Be accurate and "
    "useful. Never claim to have verified external facts, run NTSA-X orbital "
    "reasoning, or performed external actions unless independently established. "
    "NTSA-X currently has an experimental deterministic verified-compute kernel; "
    "this chat is generated by a separate local inference backend."
)


class GatewayError(Exception):
    """Safe user-facing error; omit private infrastructure details."""


def valid_session(value: object) -> str:
    if not isinstance(value, str) or SESSION.fullmatch(value) is None:
        raise GatewayError("Invalid session ID")
    return value


class TurnStore:
    """Atomic session history. Entries are NOT trusted verified evidence."""

    def __init__(self, path: str | Path):
        self.path = str(path)
        if self.path != ":memory:":
            Path(self.path).expanduser().parent.mkdir(parents=True, exist_ok=True)
        with self._connect() as db:
            db.execute("""CREATE TABLE IF NOT EXISTS dialogue (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                session_id TEXT NOT NULL,
                role TEXT NOT NULL CHECK(role IN ('user','assistant')),
                content TEXT NOT NULL,
                verification TEXT NOT NULL DEFAULT 'unverified'
                    CHECK(verification = 'unverified')
            )""")
            db.execute(
                "CREATE INDEX IF NOT EXISTS dialogue_session_idx "
                "ON dialogue(session_id, id)"
            )

    @contextmanager
    def _connect(self):
        connection = sqlite3.connect(self.path, timeout=10)
        try:
            connection.execute("PRAGMA busy_timeout = 10000")
            with connection:
                yield connection
        finally:
            connection.close()

    def history(self, session_id: str, limit: int = 24) -> list[dict]:
        valid_session(session_id)
        with self._connect() as db:
            rows = db.execute(
                "SELECT role, content FROM (SELECT id, role, content FROM "
                "dialogue WHERE session_id = ? ORDER BY id DESC LIMIT ?) "
                "ORDER BY id ASC",
                (session_id, limit),
            ).fetchall()
        return [{"role": role, "content": content} for role, content in rows]

    def commit_turn(self, session_id: str, user: str, assistant: str) -> None:
        valid_session(session_id)
        with self._connect() as db:
            db.executemany(
                "INSERT INTO dialogue(session_id, role, content) VALUES(?, ?, ?)",
                ((session_id, "user", user),
                 (session_id, "assistant", assistant)),
            )

    def clear(self, session_id: str) -> None:
        valid_session(session_id)
        with self._connect() as db:
            db.execute("DELETE FROM dialogue WHERE session_id = ?", (session_id,))


class _NoRedirect(HTTPRedirectHandler):
    """Prevent a loopback model endpoint from forwarding prompts elsewhere."""

    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


class LocalInference:
    """OpenAI-compatible streaming POST to an explicitly loopback backend."""

    def __init__(self, endpoint: str, model: str, *, timeout: float = 60,
                 max_tokens: int = 512):
        parts = urlsplit(endpoint)
        if (parts.scheme != "http"
                or parts.hostname not in ("127.0.0.1", "::1", "localhost")
                or parts.username is not None or parts.password is not None
                or parts.fragment or parts.query
                or parts.path != "/v1/chat/completions"):
            raise ValueError("Inference endpoint must be loopback /v1/chat/completions")
        if not isinstance(model, str) or not 1 <= len(model) <= 128:
            raise ValueError("Model ID must be between 1 and 128 characters")
        if not 0 < timeout <= 300:
            raise ValueError("Timeout must be in (0,300]")
        if type(max_tokens) is not int or not 1 <= max_tokens <= 4096:
            raise ValueError("Invalid local inference token limit")
        self.endpoint, self.model, self.timeout = endpoint, model, timeout
        self.max_tokens = max_tokens

    def stream(self, messages: list[dict]) -> Iterator[str]:
        payload = json.dumps({
            "model": self.model, "messages": messages,
            "stream": True, "temperature": 0.4, "max_tokens": self.max_tokens,
        }, allow_nan=False).encode("utf-8")
        request = Request(
            self.endpoint, data=payload,
            headers={"Content-Type": "application/json",
                     "Accept": "text/event-stream"},
            method="POST",
        )
        try:
            with build_opener(_NoRedirect).open(request, timeout=self.timeout) as response:
                pending: list[str] = []
                for raw in response:
                    if len(raw) > 65536:
                        raise GatewayError("Oversized inference stream frame")
                    try:
                        line = raw.decode("utf-8").rstrip("\r\n")
                    except UnicodeDecodeError as exc:
                        raise GatewayError("Invalid inference stream encoding") from exc
                    if line.startswith("data:"):
                        pending.append(line[5:].lstrip())
                    elif not line and pending:
                        data, pending = "\n".join(pending), []
                        if data == "[DONE]":
                            return
                        try:
                            packet = json.loads(data)
                            if "error" in packet:
                                raise GatewayError("Inference backend reported an error")
                            for choice in packet.get("choices", []):
                                delta = choice.get("delta", {}).get("content")
                                if isinstance(delta, str) and delta:
                                    yield delta
                        except (TypeError, ValueError, AttributeError) as exc:
                            raise GatewayError("Invalid inference stream packet") from exc
                if pending:
                    raise GatewayError("Incomplete inference stream frame")
        except HTTPError as exc:
            if exc.code == 400:
                raise GatewayError(
                    "Local model rejected the request (check context length and "
                    "model input limits)") from exc
            if exc.code == 503:
                raise GatewayError("Local inference model is busy") from exc
            raise GatewayError("Local inference model unavailable") from exc
        except (URLError, TimeoutError, OSError) as exc:
            raise GatewayError("Local inference model unavailable") from exc


class LiveService:
    """Recall before teacher inference; explicit opt-in teacher sample capture."""

    def __init__(self, store: TurnStore, inference: LocalInference | None,
                 corpus=None, student: LocalInference | None = None,
                 use_student: bool = False, identity_text: str = ""):
        if use_student and student is None:
            raise ValueError("Student endpoint required for teacher-free mode")
        if not use_student and inference is None:
            raise ValueError("Teacher endpoint required unless student mode is selected")
        if (not isinstance(identity_text, str) or
                len(identity_text.encode("utf-8")) > 1200 or
                "\x00" in identity_text):
            raise ValueError("Identity description must be at most 1200 UTF-8 bytes")
        self.identity_text = identity_text
        self.store, self.inference, self.corpus = store, inference, corpus
        self.student, self.use_student = student, use_student
        self._lock = Lock()
        self._active: set[str] = set()
        self._results: dict[str, dict] = {}

    def last_result(self, session_id: str) -> dict:
        with self._lock:
            return dict(self._results.get(session_id, {}))

    def stream(self, session_id: str, user: str, *,
               capture_for_learning: bool = False) -> Iterator[str]:
        valid_session(session_id)
        if not isinstance(user, str) or not 1 <= len(user.strip()) <= MAX_INPUT:
            raise GatewayError("Message must contain 1–4000 characters")
        if type(capture_for_learning) is not bool:
            raise GatewayError("Invalid learning consent field")
        user = user.strip()
        with self._lock:
            if session_id in self._active:
                raise GatewayError("This session already has an active response")
            self._active.add(session_id)
            self._results.pop(session_id, None)
        try:
            history = self.store.history(session_id)
            cached = (self.corpus.recall(session_id, user, history)
                      if self.corpus else None)
            source = ("approved-recall" if cached is not None else
                      ("student" if self.use_student else "teacher"))
            engine = self.student if self.use_student else self.inference
            identity = ("\nIdentity card supplied by the local operator "
                        "(unverified as learned knowledge): " + self.identity_text
                        if self.identity_text else "")
            messages = [{"role": "system",
                         "content": SYSTEM_MESSAGE + identity}]
            messages.extend(history)
            messages.append({"role": "user", "content": user})
            stream = [cached] if cached is not None else engine.stream(messages)
            output: list[str] = []
            length = 0
            for chunk in stream:
                if not isinstance(chunk, str):
                    raise GatewayError("Invalid inference output")
                length += len(chunk)
                if length > MAX_REPLY:
                    raise GatewayError("Inference reply exceeded local limit")
                output.append(chunk)
                yield chunk
            if not output:
                raise GatewayError("Inference returned an empty reply")
            answer = "".join(output)
            self.store.commit_turn(session_id, user, answer)
            sample = None
            if capture_for_learning and self.corpus and source == "teacher":
                # Never treat collection failure as a verified answer.
                sample = self.corpus.capture(
                    session_id, user, answer, history, engine.model)
            with self._lock:
                self._results[session_id] = {
                    "saved": True, "verified": False, "source": source,
                    "sample_id": sample}
        finally:
            with self._lock:
                self._active.discard(session_id)


def make_handler(service: LiveService, *, port: int):
    """Restrict the demo HTTP interface to local browser origins."""

    class Handler(BaseHTTPRequestHandler):
        protocol_version = "HTTP/1.1"

        def _allowed(self) -> bool:
            host = self.headers.get("Host", "")
            if host not in (f"127.0.0.1:{port}", f"localhost:{port}"):
                return False
            origin = self.headers.get("Origin")
            return origin is None or origin in (
                f"http://127.0.0.1:{port}", f"http://localhost:{port}"
            )

        def _json(self, status: int, value: dict | list):
            raw = json.dumps(value, ensure_ascii=False).encode("utf-8")
            self.send_response(status)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            self.send_header("Content-Length", str(len(raw)))
            self.end_headers()
            self.wfile.write(raw)

        def _body(self):
            if self.headers.get("Content-Type", "").split(";")[0] != "application/json":
                raise GatewayError("Expected JSON content type")
            try:
                length = int(self.headers.get("Content-Length", "-1"))
            except ValueError as exc:
                raise GatewayError("Invalid content length") from exc
            if not 0 <= length <= MAX_BODY:
                raise GatewayError("JSON request too large")
            try:
                data = json.loads(self.rfile.read(length))
            except (ValueError, UnicodeDecodeError) as exc:
                raise GatewayError("Invalid JSON request") from exc
            if not isinstance(data, dict):
                raise GatewayError("Expected JSON object")
            return data

        def do_GET(self):
            if not self._allowed():
                self._json(403, {"error": "Forbidden"})
                return
            if self.path == "/":
                page = Path(__file__).with_name("live_ui.html").read_bytes()
                self.send_response(200)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Content-Security-Policy",
                                 "default-src 'self'; style-src 'unsafe-inline'; "
                                 "script-src 'unsafe-inline'; connect-src 'self'; "
                                 "img-src 'none'; object-src 'none'; frame-ancestors 'none'")
                self.send_header("Cache-Control", "no-store")
                self.send_header("Content-Length", str(len(page)))
                self.end_headers()
                self.wfile.write(page)
            elif self.path == "/api/health":
                self._json(200, {"status": "ok", "mode": "local-research",
                                 "verification": "unverified-conversation"})
            else:
                self._json(404, {"error": "Not found"})

        def do_POST(self):
            if not self._allowed():
                self._json(403, {"error": "Forbidden"})
                return
            try:
                body = self._body()
                if self.path == "/api/clear":
                    session_id = valid_session(body.get("session_id"))
                    with service._lock:
                        if session_id in service._active:
                            raise GatewayError("Cannot clear an active session")
                    service.store.clear(session_id)
                    if service.corpus:
                        service.corpus.clear(session_id)
                    self._json(200, {"cleared": True})
                    return
                if self.path == "/api/approve":
                    if service.corpus is None:
                        raise GatewayError("Learning corpus is disabled")
                    accepted = service.corpus.approve(
                        valid_session(body.get("session_id")),
                        body.get("sample_id"), body.get("rights_confirmed"),
                        share=body.get("share", False))
                    self._json(200 if accepted else 404,
                               {"approved": accepted, "verified": False})
                    return
                if self.path != "/api/chat":
                    self._json(404, {"error": "Not found"})
                    return
                session = valid_session(body.get("session_id"))
                user = body.get("message")
                learn = body.get("learn", False)
                if type(learn) is not bool:
                    raise GatewayError("Invalid learning consent")
                if not isinstance(user, str) or not 1 <= len(user.strip()) <= MAX_INPUT:
                    raise GatewayError("Message must contain 1–4000 characters")
            except GatewayError as exc:
                self._json(400, {"error": str(exc)})
                return

            self.send_response(200)
            self.send_header("Content-Type", "text/event-stream; charset=utf-8")
            self.send_header("Cache-Control", "no-cache, no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            self.send_header("Connection", "close")
            self.end_headers()
            self.close_connection = True
            try:
                for token in service.stream(session, user, capture_for_learning=learn):
                    self._event("delta", {"text": token})
                self._event("done", service.last_result(session))
            except GatewayError as exc:
                self._event("error", {"error": str(exc)})
            except (OSError, BrokenPipeError, ConnectionResetError):
                pass
            except Exception:
                self._event("error", {"error": "Unexpected gateway failure"})

        def _event(self, event: str, payload: dict):
            wire = ("event: " + event + "\n" +
                    "data: " + json.dumps(payload, ensure_ascii=False) +
                    "\n\n").encode("utf-8")
            self.wfile.write(wire)
            self.wfile.flush()

        def log_message(self, _format, *_args):
            pass  # Do not log user message bodies to stdout.

    return Handler


def main() -> None:
    parser = ArgumentParser(description="NTSA-X local streaming conversation bridge")
    parser.add_argument("--port", type=int, default=8765)
    parser.add_argument("--db", default=str(Path.home() / ".kindred" / "ntsa-live.sqlite3"))
    parser.add_argument("--corpus-db",
                        default=str(Path.home() / ".kindred" / "ntsa-learning.sqlite3"))
    parser.add_argument("--identity-file",
                        help="Optional local UTF-8 identity card; operator-authored "
                             "context only, NOT trained knowledge")
    parser.add_argument("--model",
                        help="Teacher model ID hosted by your local OpenAI-compatible server")
    parser.add_argument("--student-model",
                        help="Local student model ID; evaluated and licensed separately")
    parser.add_argument("--student-max-tokens", type=int, default=128,
                        help="Maximum student output bytes/tokens requested (default 128)")
    parser.add_argument("--student-endpoint",
                        default="http://127.0.0.1:8081/v1/chat/completions")
    parser.add_argument("--use-student", action="store_true",
                        help="Manually select student; never calls the teacher")
    parser.add_argument("--endpoint", default="http://127.0.0.1:8080/v1/chat/completions")
    args = parser.parse_args()
    if not 1024 <= args.port <= 65535:
        parser.error("Port must be between 1024 and 65535")
    if args.use_student and not args.student_model:
        parser.error("--use-student requires --student-model")
    if not args.use_student and not args.model:
        parser.error("Teacher mode requires --model")
    from .learning import LearningCorpus
    teacher = LocalInference(args.endpoint, args.model) if args.model else None
    student = (LocalInference(args.student_endpoint, args.student_model,
                              max_tokens=args.student_max_tokens)
               if args.student_model else None)
    identity_text = ""
    if args.identity_file:
        path = Path(args.identity_file).expanduser().resolve()
        if not path.is_file() or path.stat().st_size > 1200:
            parser.error("Identity file must be an existing UTF-8 file <=1200 bytes")
        try:
            identity_text = path.read_text(encoding="utf-8-sig").strip()
        except UnicodeError:
            parser.error("Identity file must contain valid UTF-8 text")
    service = LiveService(TurnStore(args.db), teacher, LearningCorpus(args.corpus_db),
                          student=student, use_student=args.use_student,
                          identity_text=identity_text)
    server = ThreadingHTTPServer(
        ("127.0.0.1", args.port), make_handler(service, port=args.port)
    )
    server.daemon_threads = True
    print(f"NTSA-X local interface: http://127.0.0.1:{args.port}", flush=True)
    print("Conversation output is unverified; verified Nexus DAG remains separate.")
    try:
        server.serve_forever(poll_interval=0.2)
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
